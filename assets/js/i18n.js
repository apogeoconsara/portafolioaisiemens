let CURRENT_LANG = "en";

function t(key, vars) {
  const dict = I18N[CURRENT_LANG] || I18N.en;
  let str = dict[key] ?? I18N.en[key] ?? key;
  if (vars) {
    Object.keys(vars).forEach(k => {
      str = str.replace(new RegExp(`{{${k}}}`, "g"), vars[k]);
    });
  }
  return str;
}

function setLang(lang) {
  CURRENT_LANG = lang === "es" ? "es" : "en";
}
